-- Generates the reference pages in docs/reference/ from the live config, so they can't drift.
--
--   nvim --headless --cmd "luafile docs/scripts/generate.lua"
--
-- Runs before init.lua (--cmd) to record every vim.keymap.set call, then waits for
-- startup to finish and reads the rest from lazy.nvim, vim.lsp, conform and nvim-lint.
-- `npm run docs:gen` in docs/ runs it; CI runs it before every Pages deploy.

local REPO = "https://github.com/Venkat-Rajgopal/nvim.init"
local script = vim.uv.fs_realpath(debug.getinfo(1, "S").source:sub(2))
local docs = vim.fs.dirname(vim.fs.dirname(script))
local out_dir = docs .. "/reference"
local config_dir = vim.uv.fs_realpath(vim.fn.stdpath("config"))

-- 1. Record keymaps set from config files (lazy.nvim `keys` specs are read later) --------

local recorded = {}
local scope -- set while firing autocmds below, to label buffer-local keymaps

local keymap_set = vim.keymap.set
---@diagnostic disable-next-line: duplicate-set-field
vim.keymap.set = function(mode, lhs, rhs, opts)
  local info = debug.getinfo(2, "S")
  local src = info and info.source:sub(1, 1) == "@" and vim.uv.fs_realpath(info.source:sub(2))
  if src and vim.startswith(src, config_dir .. "/") and opts and opts.desc then
    table.insert(recorded, {
      modes = type(mode) == "table" and mode or { mode },
      lhs = lhs,
      desc = opts.desc,
      source = { file = src:sub(#config_dir + 2) },
      scope = opts.buffer and (scope or "Buffer-local") or nil,
    })
  end
  return keymap_set(mode, lhs, rhs, opts)
end

local commands = {} -- user commands created from config files
local create_command = vim.api.nvim_create_user_command
vim.api.nvim_create_user_command = function(name, cmd, opts)
  local info = debug.getinfo(2, "S")
  local src = info and info.source:sub(1, 1) == "@" and vim.uv.fs_realpath(info.source:sub(2))
  if src and vim.startswith(src, config_dir .. "/") then
    table.insert(commands, { name = name, desc = opts and opts.desc or "", file = src:sub(#config_dir + 2) })
  end
  return create_command(name, cmd, opts)
end

-- 2. Helpers ---------------------------------------------------------------------------

local function read(path)
  local f = io.open(path, "r")
  if not f then
    return nil
  end
  local s = f:read("*a")
  f:close()
  return s
end

local function write(name, lines)
  local f = assert(io.open(out_dir .. "/" .. name, "w"))
  f:write(table.concat(lines, "\n"), "\n")
  f:close()
  io.stdout:write("wrote docs/reference/" .. name .. "\n")
end

local function header(title, intro)
  return {
    "---",
    "editLink: false",
    "---",
    "",
    "<!-- Generated by docs/scripts/generate.lua from the config. Don't edit: change the config instead. -->",
    "",
    "# " .. title,
    "",
    intro,
    "",
  }
end

-- Text for a table cell: no pipes or newlines, and no raw `<` (Vue would read it as a tag)
local function cell(s) return (tostring(s):gsub("|", "\\|"):gsub("\n", " "):gsub("<", "&lt;")) end
local function code(s) return "`" .. tostring(s):gsub("|", "\\|") .. "`" end
local function file_link(file) return ("[%s](%s/blob/main/%s)"):format(code(file), REPO, file) end

local function plugin_link(p)
  local url = (p.url or ""):gsub("%.git$", "")
  return url ~= "" and ("[%s](%s)"):format(p.name, url) or p.name
end

-- The lua/plugins/*.lua files with a top-level spec for this plugin (snacks.nvim has two).
-- Mentions inside `dependencies = { ... }` don't count.
local plugin_files = {}
local function files_of(p)
  if plugin_files[p.name] then
    return plugin_files[p.name]
  end
  local short = (p.url or ""):match("github%.com/(.-)%.git$") or (p.url or ""):match("github%.com/(.-)$")
  local found = {}
  for _, path in ipairs(vim.fn.glob(config_dir .. "/lua/plugins/*.lua", false, true)) do
    for line in (read(path) or ""):gmatch("[^\n]+") do
      local lead = short and line:match('^(%s*{?%s*)"' .. vim.pesc(short) .. '"')
      if lead then
        table.insert(found, path:sub(#config_dir + 2))
        break
      end
    end
  end
  if #found == 0 and p.name == "lazy.nvim" then
    found = { "lua/insomnia/lazy.lua" }
  end
  plugin_files[p.name] = found
  return found
end

-- The file a lazy `keys` entry comes from: the plugin's spec file that has its desc
local function key_file(p, desc)
  local files = files_of(p)
  for _, file in ipairs(files) do
    if (read(config_dir .. "/" .. file) or ""):find('desc = "' .. desc .. '"', 1, true) then
      return file
    end
  end
  return files[1]
end

-- 3. Pages -----------------------------------------------------------------------------

-- lazy.nvim isn't on the runtimepath yet when this file runs (--cmd), so require late
local Config = setmetatable({}, { __index = function(_, k) return require("lazy.core.config")[k] end })
local function opts_of(name)
  local p = Config.plugins[name]
  return p and require("lazy.core.plugin").values(p, "opts", false) or {}
end

local function sorted_plugins()
  local list = vim.tbl_values(Config.plugins)
  table.sort(list, function(a, b) return a.name:lower() < b.name:lower() end)
  return list
end

local function keymaps_page()
  -- Fire what normally sets buffer-local keymaps, on scratch buffers
  local buf = vim.api.nvim_create_buf(true, false)
  vim.api.nvim_set_current_buf(buf)
  scope = "When a language server attaches"
  vim.api.nvim_exec_autocmds("LspAttach", { buffer = buf, data = { client_id = -1 } })

  local md = vim.api.nvim_create_buf(true, false)
  vim.api.nvim_set_current_buf(md)
  scope = "In Markdown files"
  vim.bo[md].filetype = "markdown"

  for _, p in ipairs(sorted_plugins()) do
    local on_attach = opts_of(p.name).on_attach
    if type(on_attach) == "function" then
      scope = "Where " .. p.name .. " is active"
      pcall(on_attach, vim.api.nvim_create_buf(true, false))
    end
  end
  scope = nil

  -- lazy.nvim `keys = { ... }` specs
  local maps = vim.deepcopy(recorded)
  for _, p in ipairs(sorted_plugins()) do
    for _, k in pairs(p._.handlers and p._.handlers.keys or {}) do
      if k.desc and k.desc ~= "which_key_ignore" then
        local modes = type(k.mode) == "table" and k.mode or { k.mode or "n" }
        table.insert(maps, { modes = modes, lhs = k.lhs, desc = k.desc, source = { plugin = p } })
      end
    end
  end

  -- One row per key + action, all its modes together
  local rows, seen = {}, {}
  for _, m in ipairs(maps) do
    local id = m.lhs .. "\0" .. m.desc .. "\0" .. (m.scope or "")
    if seen[id] then
      for _, mode in ipairs(m.modes) do
        if not vim.list_contains(seen[id].modes, mode) then
          table.insert(seen[id].modes, mode)
        end
      end
    else
      seen[id] = vim.deepcopy(m, true)
      seen[id].source = m.source
      table.insert(rows, seen[id])
    end
  end

  -- Group like which-key does
  local groups = {}
  for _, g in ipairs(opts_of("which-key.nvim").spec or {}) do
    if g.group then
      table.insert(groups, { prefix = g[1], name = g.group, rows = {} })
    end
  end
  table.sort(groups, function(a, b) return #a.prefix > #b.prefix end) -- longest prefix wins
  local other = { name = "other", rows = {} }
  for _, r in ipairs(rows) do
    local target = other
    for _, g in ipairs(groups) do
      if vim.startswith(r.lhs, g.prefix) and #r.lhs > #g.prefix then
        target = g
        break
      end
    end
    table.insert(target.rows, r)
  end
  table.sort(groups, function(a, b) return a.prefix < b.prefix end)
  table.insert(groups, other)

  local mode_names = { n = "normal", v = "visual", x = "visual", i = "insert", t = "terminal", o = "operator" }
  local lines = header(
    "Keymaps",
    "Every mapping this config adds, grouped the way which-key shows them. `<leader>` is `Space`."
      .. " Press `<leader>` and wait to see the same list inside Neovim, or `<leader>fk` to search it."
  )
  for _, g in ipairs(groups) do
    if #g.rows > 0 then
      table.sort(g.rows, function(a, b) return a.lhs:lower() < b.lhs:lower() end)
      table.insert(
        lines,
        ("## %s%s"):format(g.name:sub(1, 1):upper() .. g.name:sub(2), g.prefix and (" `" .. g.prefix .. "`") or "")
      )
      table.insert(lines, "")
      table.insert(lines, "| Keys | Action | Mode | Where | Defined in |")
      table.insert(lines, "| --- | --- | --- | --- | --- |")
      for _, r in ipairs(g.rows) do
        local modes = vim.tbl_map(function(m) return mode_names[m] or m end, r.modes)
        local p = r.source.plugin
        local file = p and key_file(p, r.desc)
        local src = p and (plugin_link(p) .. (file and (" (" .. file_link(file) .. ")") or ""))
          or file_link(r.source.file)
        table.insert(
          lines,
          ("| %s | %s | %s | %s | %s |"):format(
            code(r.lhs),
            cell(r.desc),
            table.concat(vim.fn.uniq(modes), ", "),
            cell(r.scope or "Everywhere"),
            src
          )
        )
      end
      table.insert(lines, "")
    end
  end
  -- blink.cmp keys only act while the completion menu is open, so they get their own table
  local blink = opts_of("blink.cmp").keymap or {}
  local keys = vim.tbl_filter(function(k) return k ~= "preset" end, vim.tbl_keys(blink))
  if #keys > 0 then
    table.sort(keys)
    table.insert(lines, "## Completion menu")
    table.insert(lines, "")
    table.insert(
      lines,
      "In insert mode and on the `:` line, from [blink.cmp](https://github.com/saghen/blink.cmp)"
        .. " ("
        .. file_link("lua/plugins/completion.lua")
        .. "). Each key tries its actions in order;"
        .. " `fallback` means the key does what it normally does."
    )
    table.insert(lines, "")
    table.insert(lines, "| Keys | Actions |")
    table.insert(lines, "| --- | --- |")
    for _, k in ipairs(keys) do
      local actions = vim.tbl_map(function(a) return type(a) == "string" and code(a) or "custom" end, blink[k])
      table.insert(lines, ("| %s | %s |"):format(code(k), table.concat(actions, " → ")))
    end
    table.insert(lines, "")
  end
  write("keymaps.md", lines)
end

local function plugins_page()
  local lock = vim.json.decode(read(config_dir .. "/lazy-lock.json") or "{}")
  local by_file, files = {}, {}
  for _, p in ipairs(sorted_plugins()) do
    local list = files_of(p)
    for _, file in ipairs(#list > 0 and list or { "Dependencies" }) do
      if not by_file[file] then
        by_file[file] = {}
        table.insert(files, file)
      end
      table.insert(by_file[file], p)
    end
  end
  table.sort(files, function(a, b)
    if a == "Dependencies" or b == "Dependencies" then
      return b == "Dependencies"
    end
    return a < b
  end)

  local function sorted_keys(t)
    local keys = vim.tbl_keys(t)
    table.sort(keys)
    return keys
  end

  local function loads(p)
    if p.lazy == false or p.name == "lazy.nvim" then
      return "at startup"
    end
    local h, parts = p._.handlers or {}, {}
    if h.event then
      table.insert(parts, "on " .. table.concat(vim.tbl_map(code, sorted_keys(h.event)), ", "))
    end
    if h.ft then
      table.insert(parts, "for " .. table.concat(vim.tbl_map(code, sorted_keys(h.ft)), ", ") .. " files")
    end
    if h.cmd then
      table.insert(
        parts,
        "on " .. table.concat(vim.tbl_map(function(c) return code(":" .. c) end, sorted_keys(h.cmd)), ", ")
      )
    end
    if h.keys and next(h.keys) then
      table.insert(parts, "on its keys")
    end
    if #parts > 0 then
      return table.concat(parts, "; ")
    end
    return vim.uv.fs_stat(p.dir .. "/colors") and "when picked as the colorscheme" or "when another plugin needs it"
  end

  local lines = header(
    "Plugins",
    ("All %d plugins, by the file that sets them up, with the commit pinned in `lazy-lock.json`."):format(
      #vim.tbl_keys(Config.plugins)
    ) .. " Most load only when needed; `:Lazy profile` shows what each one costs at startup."
  )
  for _, file in ipairs(files) do
    table.insert(lines, "## " .. (file == "Dependencies" and "Dependencies" or file_link(file)))
    table.insert(lines, "")
    table.insert(lines, "| Plugin | Loads | Pinned |")
    table.insert(lines, "| --- | --- | --- |")
    for _, p in ipairs(by_file[file]) do
      local commit = lock[p.name] and lock[p.name].commit
      local url = (p.url or ""):gsub("%.git$", "")
      local pin = commit and ("[%s](%s/commit/%s)"):format(code(commit:sub(1, 7)), url, commit) or ""
      table.insert(lines, ("| %s | %s | %s |"):format(plugin_link(p), loads(p), pin))
    end
    table.insert(lines, "")
  end
  write("plugins.md", lines)
end

local function languages_page()
  local lines = header(
    "Languages",
    "Language servers, formatters and linters per file type, as configured right now."
      .. " On a Raspberry Pi, `ty` replaces `basedpyright` (see [Raspberry Pi](/guide/raspberry-pi))."
  )

  -- Language servers enabled with vim.lsp.enable() in lua/insomnia/lsp/
  local mason = opts_of("mason-lspconfig.nvim").ensure_installed or {}
  local lsp_files = vim.fn.glob(config_dir .. "/lua/insomnia/lsp/*.lua", false, true)
  local names = {}
  for _, path in ipairs(vim.api.nvim_get_runtime_file("lsp/*.lua", true)) do
    local name = vim.fn.fnamemodify(path, ":t:r")
    if vim.lsp.is_enabled(name) and not vim.list_contains(names, name) then
      table.insert(names, name)
    end
  end
  table.sort(names)
  table.insert(lines, "## Language servers")
  table.insert(lines, "")
  table.insert(lines, "| Server | File types | Installed by | Configured in |")
  table.insert(lines, "| --- | --- | --- | --- |")
  for _, name in ipairs(names) do
    local cfg = vim.lsp.config[name] or {}
    local where = ""
    for _, path in ipairs(lsp_files) do
      if (read(path) or ""):find('vim.lsp.enable("' .. name .. '")', 1, true) then
        where = file_link(path:sub(#config_dir + 2))
      end
    end
    table.insert(
      lines,
      ("| %s | %s | %s | %s |"):format(
        code(name),
        table.concat(vim.tbl_map(code, cfg.filetypes or {}), ", "),
        vim.list_contains(mason, name) and "Mason" or "you (see the file)",
        where
      )
    )
  end
  table.insert(lines, "")

  -- Formatters (conform.nvim)
  require("lazy").load({ plugins = { "conform.nvim", "nvim-lint" } })
  local by_ft = require("conform").formatters_by_ft
  local fts = vim.tbl_keys(by_ft)
  table.sort(fts)
  table.insert(lines, "## Formatters")
  table.insert(lines, "")
  table.insert(lines, "Run on save by conform.nvim, in this order, and on demand with `<leader>cf`.")
  table.insert(
    lines,
    "Markdown and `lazy-lock.json` are only formatted on demand. Other file types use the language server's formatter, if it has one."
  )
  table.insert(lines, "")
  table.insert(lines, "| File type | Formatters |")
  table.insert(lines, "| --- | --- |")
  for _, ft in ipairs(fts) do
    local list = type(by_ft[ft]) == "table" and by_ft[ft] or {}
    table.insert(lines, ("| %s | %s |"):format(code(ft), table.concat(vim.tbl_map(code, list), " → ")))
  end
  table.insert(lines, "")

  -- Linters (nvim-lint); servers lint the rest
  local linters = require("lint").linters_by_ft
  fts = vim.tbl_keys(linters)
  table.sort(fts)
  table.insert(lines, "## Linters")
  table.insert(lines, "")
  table.insert(
    lines,
    "Run by nvim-lint for file types without a linting language server. Results are normal diagnostics (`gl`, `[d`, `]d`)."
  )
  table.insert(lines, "")
  table.insert(lines, "| File type | Linters |")
  table.insert(lines, "| --- | --- |")
  for _, ft in ipairs(fts) do
    table.insert(lines, ("| %s | %s |"):format(code(ft), table.concat(vim.tbl_map(code, linters[ft]), ", ")))
  end
  table.insert(lines, "")
  write("languages.md", lines)
end

local function options_page()
  local lines = header(
    "Options and commands",
    "Editor settings from " .. file_link("lua/insomnia/options.lua") .. ". Check any of them with `:set <name>?`."
  )
  table.insert(lines, "## Options")
  table.insert(lines, "")
  table.insert(lines, "| Option | Value | Why |")
  table.insert(lines, "| --- | --- | --- |")
  for line in (read(config_dir .. "/lua/insomnia/options.lua") or ""):gmatch("[^\n]+") do
    local name, comment = line:match("^opt%.([%w_]+)%s*=.-%-%-%s*(.*)$")
    name = name or line:match("^opt%.([%w_]+)%s*=")
    if name then
      table.insert(lines, ("| %s | %s | %s |"):format(code(name), code(vim.o[name]), cell(comment or "")))
    end
  end
  table.insert(lines, "")

  table.sort(commands, function(a, b) return a.name < b.name end)
  if #commands > 0 then
    table.insert(lines, "## Commands added by this config")
    table.insert(lines, "")
    table.insert(lines, "Plugin commands (`:Lazy`, `:Mason`, `:Telescope`, ...) are in the guides.")
    table.insert(lines, "")
    table.insert(lines, "| Command | Action | Defined in |")
    table.insert(lines, "| --- | --- | --- |")
    for _, c in ipairs(commands) do
      table.insert(lines, ("| %s | %s | %s |"):format(code(":" .. c.name), cell(c.desc), file_link(c.file)))
    end
    table.insert(lines, "")
  end
  write("options.md", lines)
end

local function themes_page()
  local lines = header(
    "Themes",
    "Colorschemes from "
      .. file_link("lua/plugins/colorscheme.lua")
      .. ". Pick one with `<leader>th`; the choice is remembered."
  )
  table.insert(lines, "| Theme | Variants (`:colorscheme <name>`) |")
  table.insert(lines, "| --- | --- |")
  for _, p in ipairs(sorted_plugins()) do
    if vim.list_contains(files_of(p), "lua/plugins/colorscheme.lua") then
      local variants = vim.tbl_map(
        function(f) return code(vim.fn.fnamemodify(f, ":t:r")) end,
        vim.fn.glob(p.dir .. "/colors/*.{lua,vim}", false, true)
      )
      table.insert(
        lines,
        ("| %s | %s |"):format(plugin_link(p), table.concat(vim.fn.uniq(vim.fn.sort(variants)), ", "))
      )
    end
  end
  table.insert(lines, "")
  write("themes.md", lines)
end

-- 4. Run after startup -----------------------------------------------------------------

vim.api.nvim_create_autocmd("VimEnter", {
  once = true,
  callback = function()
    vim.schedule(function()
      vim.fn.mkdir(out_dir, "p")
      local ok, err = xpcall(function()
        keymaps_page()
        plugins_page()
        languages_page()
        options_page()
        themes_page()
      end, debug.traceback)
      if not ok then
        io.stderr:write("docs generation failed:\n" .. err .. "\n")
        vim.cmd("cquit 1")
      end
      vim.cmd("qall!")
    end)
  end,
})
